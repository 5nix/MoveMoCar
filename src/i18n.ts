export type MessageKey = keyof typeof zhCNMessages;
export type Messages = Record<MessageKey, string>;

// Non-Chinese dictionaries are populated below. Keeping this typed makes a
// missing translation a compile-time error when the source dictionary grows.
export const messages = {
  "zh-CN": zhCNMessages,
  ...translations,
} satisfies Record<Locale, Messages>;

export const t = (
  locale: Locale,
  key: MessageKey,
  parameters: Record<string, string | number> = {},
) => {
  const template: string = messages[locale]?.[key] ?? messages[defaultLocale][key];
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) =>
    Object.hasOwn(parameters, name) ? String(parameters[name]) : match,
  );
};
